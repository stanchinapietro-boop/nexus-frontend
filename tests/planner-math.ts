import assert from "node:assert/strict";
import {budget, classify, defaults, emptyPlace, monday, remainingEstimate} from "../src/planner";
const day="2026-11-19", plan={...defaults,start_min:540,end_min:660};
const task={key:"school-1",title:"Capitolo",source:"Academic",to:"/academic",due:day,important:true,done:false,minutes:120};
const evt=(id:number,a:string,b:string)=>({id,title:"Studio",category:"studio",description:"",location:"",starts_at:day+"T"+a,ends_at:day+"T"+b});
const events=[evt(1,"08:45","10:00"),evt(2,"09:30","10:30")];
const link=(id:number)=>({event_id:id,source_key:task.key,project_id:null,color:"#ffffff"});
assert.equal(monday("2026-11-22"),"2026-11-16");
assert.equal(monday("2026-11-23"),"2026-11-23");
assert.equal(classify(task,day).q,1);
assert.equal(classify({...task,due:"2027-04-01"},day).q,2);
assert.equal(classify({...task,important:false},day).q,3);
assert.equal(classify({...task,important:false,due:null},day).q,4);
assert.equal(classify(task,day,{...emptyPlace(task.key),quadrant:4}).q,4);
assert.equal(budget(day,defaults,events,0),null);
assert.deepEqual(budget(day,plan,events,45),{capacity:120,occupied:90,remaining:-15});
assert.equal(remainingEstimate(day,plan,events,[link(1)],task.key,120),60);
assert.equal(remainingEstimate(day,plan,events,[link(1),link(2)],task.key,120),30);
assert.equal(remainingEstimate(day,plan,events,[link(1)],"school-2",45),45);
